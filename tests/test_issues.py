"""The "Log an issue" file writer."""

from datetime import datetime

import pytest

from paratext.ai.providers import ProviderError
from paratext.issues import HEADER, IssueContext, issues_path, log_issue, repo_root
from paratext.testing import FakeIssueProvider

WHEN = datetime(2026, 11, 4, 9, 30)


def context():
    return IssueContext("A Study of Catalysis", "/p/paper.pdf", 2, 9, "fake", "a chemist", "limiting potential")


def test_log_issue_with_ai_writeup(tmp_path):
    path = tmp_path / "issues.md"
    provider = FakeIssueProvider()
    got, problem = log_issue("tooltip covers the word I'm hovering", context(), provider, path, now=WHEN)
    assert got == path and problem is None
    text = path.read_text()
    assert text.startswith(HEADER)
    assert "## 2026-11-04 09:30 — Tooltip hides page text" in text
    assert "- **Category:** ui\n- **Status:** open" in text
    assert "Paper: A Study of Catalysis (page 2 of 9), `/p/paper.pdf`" in text
    assert "AI: fake; audience: a chemist" in text and "Side panel showed: limiting potential" in text
    assert "> tooltip covers the word I'm hovering" in text
    assert "**Write-up (AI-generated by fake):** The tooltip covers the term." in text
    prompt = provider.calls[0]["prompt"]
    assert "<note>\ntooltip covers the word I'm hovering\n</note>" in prompt and "page 2 of 9" in prompt
    assert provider.calls[0]["json_schema"]["required"] == ["title", "category", "description"]
    # a second entry is appended, the header is not repeated
    log_issue("second note", context(), provider, path, now=WHEN)
    assert path.read_text().count("# Reported issues") == 1 and path.read_text().count("## 2026-11-04") == 2


def test_log_issue_without_ai_or_with_failing_ai(tmp_path):
    path = tmp_path / "issues.md"
    _, problem = log_issue("  the page jumps  ", IssueContext(), None, path, now=WHEN)
    assert problem is None
    text = path.read_text()
    assert "## 2026-11-04 09:30 — the page jumps" in text and "Write-up" not in text and "Paper:" not in text
    _, problem = log_issue("x", IssueContext(), FakeIssueProvider(error=ProviderError("quota")), path, now=WHEN)
    assert problem == "quota" and "*No AI write-up: quota*" in path.read_text()
    with pytest.raises(ValueError):
        log_issue("   ", IssueContext(), None, path)


def test_issues_path(monkeypatch, tmp_path):
    monkeypatch.setenv("PARATEXT_ISSUES", str(tmp_path / "x.md"))
    assert issues_path() == tmp_path / "x.md"
    monkeypatch.delenv("PARATEXT_ISSUES")
    root = repo_root()
    if root is not None:  # editable install: the file lives with the other notes
        assert issues_path() == root / "notes" / "ReportedIssues.md"
