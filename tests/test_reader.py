def test_zoom_and_render(window_factory, qtbot):
    window = window_factory(FakeProvider())
    before = window.view.zoom_factor()
    window.view.zoom_by(2)
    assert window.view.zoom_factor() == pytest.approx(before * 2)
    qtbot.waitUntil(lambda: any(k[0] == 0 for k in window.view.cache.items))
    page, scale = next(k for k in window.view.cache.items if k[0] == 0)
    assert window.view.cache.items[(page, scale)].width() > 0


