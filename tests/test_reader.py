"""GUI tests for the PDF reader (need a Tk display)."""

import pytest

from paratext.config import Config
from paratext.engine import ImmediateExecutor
from paratext.reader.app import ReaderApp
from paratext.testing import SAMPLE_GLOSSARY, FakeProvider, make_sample_pdf


def texts(widget):
    """All label texts inside a widget tree."""
    out = []
    for child in widget.winfo_children():
        if child.winfo_class() == "Label":
            out.append(child.cget("text"))
        out.extend(texts(child))
    return out


@pytest.fixture
def app_factory(tk_root, tmp_path):
    pdf = make_sample_pdf(tmp_path / "paper.pdf")

    def make(provider=None, provider_name="fake"):
        config = Config(cache_dir=tmp_path / "cache")
        if provider is not None:
            config.make_provider = lambda name=None: None if name == "none" else provider
        app = ReaderApp(tk_root, config, pdf, provider_name, executor=ImmediateExecutor())
        app.hover_delay_ms = 0
        tk_root.update()
        app.process_pending()
        tk_root.update()
        return app

    return make


def span_center(app, key):
    span, rects = next((s, r) for s, r in app._spans if s.key == key)
    x0, y0, x1, y1 = rects[0]
    return span, int((x0 + x1) / 2 * app.zoom), int((y0 + y1) / 2 * app.zoom)


def test_terms_are_underlined(app_factory):
    app = app_factory(FakeProvider())
    keys = {s.key for s, _ in app._spans}
    assert {"oxygen reduction reaction", "limiting potential", "dft", "orr"} <= keys
    assert app.canvas.find_withtag("term")
    assert app.page_label.cget("text") == "1 / 2"
    assert "new terms" in app.status.cget("text")


def test_hover_shows_tooltip(app_factory, tk_root):
    app = app_factory(FakeProvider())
    span, x, y = span_center(app, "limiting potential")
    assert app.span_at(x / app.zoom, y / app.zoom) == span
    app.canvas.event_generate("<Motion>", x=x, y=y)
    tk_root.update()
    assert app._tooltip is not None
    shown = texts(app._tooltip)
    assert "limiting potential" in shown
    assert SAMPLE_GLOSSARY["limiting potential"] in shown
    assert any("AI-generated by fake" in t for t in shown)
    # moving off the term hides it
    app.canvas.event_generate("<Motion>", x=2, y=2)
    tk_root.update()
    assert app._tooltip is None


def test_click_term_shows_panel_then_more_depth(app_factory, tk_root):
    provider = FakeProvider(explanation="A longer explanation.")
    app = app_factory(provider)
    _, x, y = span_center(app, "limiting potential")
    app.canvas.event_generate("<ButtonPress-1>", x=x, y=y)
    app.canvas.event_generate("<ButtonRelease-1>", x=x, y=y)
    tk_root.update()
    assert app.panel_title.cget("text") == "limiting potential"
    assert app.panel_body().startswith(SAMPLE_GLOSSARY["limiting potential"])
    app.explain_deeper()
    app.process_pending()
    body = app.panel_body()
    assert SAMPLE_GLOSSARY["limiting potential"] in body and "A longer explanation." in body
    assert "Give a fuller explanation" in provider.calls[-1]["prompt"]


def test_select_and_explain(app_factory, tk_root):
    provider = FakeProvider(explanation="Single-atom catalysts are isolated metal atoms on a support.")
    app = app_factory(provider)
    words = [w.text for w in app.doc.words(0)]
    start = words.index("single-atom")
    # drag across two words
    w0, w1 = app.doc.words(0)[start], app.doc.words(0)[start + 1]
    z = app.zoom
    app.canvas.event_generate("<ButtonPress-1>", x=int((w0.x0 + 1) * z), y=int((w0.y0 + 2) * z))
    app.canvas.event_generate("<B1-Motion>", x=int((w1.x1 - 1) * z), y=int((w1.y0 + 2) * z))
    app.canvas.event_generate("<ButtonRelease-1>", x=int((w1.x1 - 1) * z), y=int((w1.y0 + 2) * z))
    tk_root.update()
    assert app.selected_text() == "single-atom catalysts."
    assert app.canvas.find_withtag("sel")
    assert not app.explain_button.instate(["disabled"])
    app.explain_selection()
    app.process_pending()
    assert app.panel_title.cget("text") == "single-atom catalysts."
    assert "isolated metal atoms" in app.panel_body()


def test_next_page_requests_and_draws_its_terms(app_factory, tk_root):
    provider = FakeProvider()
    app = app_factory(provider)
    # page 2 was prefetched together with page 1
    assert len(provider.calls) == 2
    app.go_to(1)
    tk_root.update()
    assert app.page_label.cget("text") == "2 / 2"
    assert "plane-wave basis" in {s.key for s, _ in app._spans}
    app.go_to(5)  # out of range: ignored
    assert app.page == 1


