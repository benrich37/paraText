def test_provider_change_is_saved(window_factory, tmp_path):
    window = window_factory(FakeProvider())
    window.provider_box.setCurrentText("none")
    assert window.provider_name == "none"
    assert window.info_bar.isVisible()
    saved = Config.load(tmp_path / "config.toml")
    assert saved.default_provider is None
    window.audience_edit.setText("a chemist")
    window.audience_edit.editingFinished.emit()
    assert Config.load(tmp_path / "config.toml").audience == "a chemist"


def test_setup_dialog_result_is_applied(window_factory, monkeypatch):
    window = window_factory(provider=None, provider_name="none")

    def fake_exec(dialog):
        dialog.selected_name = "mine"
        dialog.config.providers["mine"] = {"kind": "command", "command": ["definitely-missing-cmd"]}
        dialog.config.default_provider = "mine"
        dialog.config.audience = "a poet"
        return 1

    monkeypatch.setattr("paratext.reader.setup.SetupDialog.exec", fake_exec)
    window.open_setup()
    assert window.provider_name == "mine"
    assert window.provider_box.currentText() == "mine"
    assert window.audience_edit.text() == "a poet"
    assert window.engine.provider is not None
