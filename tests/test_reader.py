"""GUI tests for the Qt PDF reader (run on Qt's offscreen platform, no display needed)."""

import pytest
from PySide6.QtCore import Qt
from PySide6.QtTest import QTest
from PySide6.QtWidgets import QToolTip

from paratext.config import Config
from paratext.engine import ImmediateExecutor
from paratext.reader.app import ReaderWindow
from paratext.testing import SAMPLE_GLOSSARY, FakeProvider, make_sample_pdf


@pytest.fixture
def window_factory(qtbot, tmp_path):
    pdf = make_sample_pdf(tmp_path / "paper.pdf")

    def make(provider=None, provider_name="fake"):
        config = Config(cache_dir=tmp_path / "cache", path=tmp_path / "config.toml")
        if provider is not None:
            config.make_provider = lambda name=None: None if name == "none" else provider
        window = ReaderWindow(config, pdf, provider_name, executor=ImmediateExecutor())
        qtbot.addWidget(window)
        window.show()
        qtbot.waitExposed(window)
        return window

    return make


def term_point(window, page, key):
    """Viewport point at the centre of a term's first line box."""
    item = window.view.page_item(page)
    term = next(t for t in item.spans if t.span.key == key)
    return term, window.view.mapFromScene(item.mapToScene(term.rects[0].center()))


def word_point(window, page, index, dx):
    item = window.view.page_item(page)
    w = window.doc.words(page)[index]
    x = w.x0 + 1 if dx < 0 else w.x1 - 1
    return window.view.mapFromScene(item.mapToScene(x, w.y0 + 2))


def test_terms_are_underlined(window_factory):
    window = window_factory(FakeProvider())
    keys = {t.span.key for t in window.view.page_item(0).spans}
    assert {"oxygen reduction reaction", "limiting potential", "dft", "orr"} <= keys
    assert window.page_spin.value() == 1 and "/ 2" in window.page_count_label.text()
    assert "new terms" in window.statusBar().currentMessage()
    assert not window.info_bar.isVisible()


def test_hover_shows_tooltip(window_factory, qtbot):
    window = window_factory(FakeProvider())
    term, point = term_point(window, 0, "limiting potential")
    QTest.mouseMove(window.view.viewport(), point)
    qtbot.waitUntil(lambda: QToolTip.isVisible())
    assert window.view.page_item(0).hover_span is term
    text = QToolTip.text()
    assert "<b>limiting potential</b>" in text
    assert SAMPLE_GLOSSARY["limiting potential"] in text
    assert "AI-generated by fake" in text
    # moving off the term hides it
    QTest.mouseMove(window.view.viewport(), word_point(window, 0, 0, -1))
    qtbot.waitUntil(lambda: window.view.page_item(0).hover_span is None)


def test_acronym_tooltip_footer(window_factory, qtbot):
    window = window_factory(FakeProvider())
    _, point = term_point(window, 0, "orr")
    QTest.mouseMove(window.view.viewport(), point)
    qtbot.waitUntil(lambda: QToolTip.isVisible())
    assert "Defined in the paper" in QToolTip.text()


def test_click_term_then_more_depth(window_factory):
    provider = FakeProvider(explanation="A longer explanation.")
    window = window_factory(provider)
    _, point = term_point(window, 0, "limiting potential")
    QTest.mouseClick(window.view.viewport(), Qt.MouseButton.LeftButton, Qt.KeyboardModifier.NoModifier, point)
    assert window.panel_title.text() == "limiting potential"
    assert window.panel_body().startswith(SAMPLE_GLOSSARY["limiting potential"])
    assert window.depth_button.isEnabled()
    window.explain_deeper()
    body = window.panel_body()
    assert SAMPLE_GLOSSARY["limiting potential"] in body and "A longer explanation." in body
    assert "Give a fuller explanation" in provider.calls[-1]["prompt"]


def test_drag_select_and_explain(window_factory):
    provider = FakeProvider(explanation="Single-atom catalysts are isolated metal atoms on a support.")
    window = window_factory(provider)
    words = [w.text for w in window.doc.words(0)]
    start = words.index("single-atom")
    p0, p1 = word_point(window, 0, start, -1), word_point(window, 0, start + 1, +1)
    viewport = window.view.viewport()
    QTest.mousePress(viewport, Qt.MouseButton.LeftButton, Qt.KeyboardModifier.NoModifier, p0)
    QTest.mouseMove(viewport, p1)
    QTest.mouseRelease(viewport, Qt.MouseButton.LeftButton, Qt.KeyboardModifier.NoModifier, p1)
    assert window.selected_text() == "single-atom catalysts."
    assert window.view.selection() == (0, start, start + 1)
    assert window.explain_button.isEnabled()
    window.explain_selection()
    assert window.panel_title.text() == "single-atom catalysts."
    assert "isolated metal atoms" in window.panel_body()


