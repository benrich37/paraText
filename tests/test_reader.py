def test_hover_shows_popup_that_stays_until_dismissed(window_factory, qtbot):
    window = window_factory(FakeProvider())
    term, point = term_point(window, 0, "limiting potential")
    QTest.mouseMove(window.view.viewport(), point)
    qtbot.waitUntil(lambda: window.popup.isVisible())
    assert window.view.page_item(0).hover_span is term
    text = window.popup.text()
    assert "<b>limiting potential</b>" in text
    assert SAMPLE_GLOSSARY["limiting potential"] in text
    assert "AI-generated by fake" in text  # the provider's cache key: tool, model and effort
    # moving off the term keeps it open; a click on the page dismisses it
    QTest.mouseMove(window.view.viewport(), word_point(window, 0, 0, -1))
    qtbot.waitUntil(lambda: window.view.page_item(0).hover_span is None)
    assert window.popup.isVisible()
    QTest.mouseClick(window.view.viewport(), Qt.MouseButton.LeftButton, Qt.KeyboardModifier.NoModifier, point)
    qtbot.waitUntil(lambda: not window.popup.isVisible())
    # hovering another term shows it again; Escape dismisses it too
    _, other = term_point(window, 0, "ORR")
    QTest.mouseMove(window.view.viewport(), other)
    qtbot.waitUntil(lambda: window.popup.isVisible())
    assert "<b>ORR</b>" in window.popup.text()
    QTest.keyClick(window, Qt.Key.Key_Escape)
    assert not window.popup.isVisible()


