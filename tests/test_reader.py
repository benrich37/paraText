def test_proofread_action(window_factory):
    import json

    class Proofreader(FakeProvider):
        def complete(self, system, prompt, json_schema=None):
            if json_schema is not None and "corrections" in json_schema["properties"]:
                return json.dumps(
                    {"corrections": [{"term": "limiting potential", "action": "fix", "explanation": "Better."}]}
                )
            return super().complete(system, prompt, json_schema)

    window = window_factory(Proofreader())
    assert window.proofread_action.isEnabled()
    _, point = term_point(window, 0, "limiting potential")
    QTest.mouseClick(window.view.viewport(), Qt.MouseButton.LeftButton, Qt.KeyboardModifier.NoModifier, point)
    window.proofread_all()
    assert window.engine.entry("limiting potential").explanation == "Better."
    assert window.panel_body().startswith("Better.") and "proofread by fake" in window.panel_footer.text()
    # the term occurs on both sample pages, so it was checked (and corrected) once per page
    assert "2 corrected, 0 removed" in window.statusBar().currentMessage()


