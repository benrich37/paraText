def test_paging_and_prefetch(window_factory):
    provider = FakeProvider()
    window = window_factory(provider)
    assert len(provider.calls) == 2  # page 2 prefetched with page 1
    window.go_to(1)
    assert window.current_page() == 1 and window.page_spin.value() == 2
    assert "plane-wave basis" in {t.span.key for t in window.view.page_item(1).spans}
    window.page_spin.setValue(1)
    assert window.current_page() == 0


