"""Build a macOS application bundle that opens PDFs in the paraText reader.

``paratext install-app`` writes ``~/Applications/paraText.app``. The bundle is a thin wrapper: its executable is a
shell script that ``exec``s the Python interpreter that ran the installer (normally the project's virtualenv) with
``-m paratext read``. Because ``Info.plist`` declares the bundle as a viewer of ``com.adobe.pdf``, Finder lists it
under "Open With" and the file can be set as the default PDF app. When Finder opens a document, macOS sends an
Apple Event rather than a command-line argument; Qt turns that into a ``QFileOpenEvent``, which the reader handles
(``paratext.reader.app.FileOpenHandler``).

The script also bakes in the ``PATH`` of the shell that ran the installer, because apps started from Finder get
only the minimal system ``PATH`` and would not find subscription CLIs such as ``claude`` or ``codex``. Output goes
to ``~/Library/Logs/paraText.log`` (there is no terminal to show a traceback).
"""

from __future__ import annotations

import os
import plistlib
import shutil
import subprocess
import sys
from pathlib import Path

from paratext import __version__

BUNDLE_ID = "org.paratext.reader"
APP_NAME = "paraText"
EXECUTABLE = "paratext"
ICON_FILE = "paratext.icns"
LSREGISTER = (
    "/System/Library/Frameworks/CoreServices.framework/Versions/A/Frameworks/LaunchServices.framework"
    "/Versions/A/Support/lsregister"
)

LAUNCHER = """#!/bin/sh
# Generated by `paratext install-app`; rerun it after moving the project or its virtualenv.
# Finder gives apps a minimal PATH, so the PATH of the installing shell is restored here (subscription CLIs).
export PATH={path}
export PARATEXT_PYTHON={python}
# Apps started from Finder have no terminal: keep tracebacks and "opened ..." lines in a log file.
export PARATEXT_LOG="${{PARATEXT_LOG:-INFO}}"
mkdir -p "$HOME/Library/Logs"
exec "$PARATEXT_PYTHON" -m paratext read "$@" >> "$HOME/Library/Logs/paraText.log" 2>&1
"""


def default_app_path() -> Path:
    return Path.home() / "Applications" / f"{APP_NAME}.app"


def info_plist(icon: bool) -> dict:
    plist = {
        "CFBundleDevelopmentRegion": "en",
        "CFBundleDisplayName": APP_NAME,
        "CFBundleExecutable": EXECUTABLE,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleInfoDictionaryVersion": "6.0",
        "CFBundleName": APP_NAME,
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": __version__,
        "CFBundleVersion": __version__,
        "LSMinimumSystemVersion": "11.0",
        "NSHighResolutionCapable": True,
        "NSSupportsAutomaticGraphicsSwitching": True,
        # Declare PDF support so the app appears in "Open With" and can be chosen as the default PDF viewer.
        # "Alternate" means it does not claim to be the default; the user can still pick it in Get Info.
        "CFBundleDocumentTypes": [
            {
                "CFBundleTypeName": "PDF document",
                "CFBundleTypeRole": "Viewer",
                "LSHandlerRank": "Alternate",
                "LSItemContentTypes": ["com.adobe.pdf"],
            }
        ],
    }
    if icon:
        plist["CFBundleIconFile"] = ICON_FILE
    return plist


def _shell_quote(s: str) -> str:
    return "'" + s.replace("'", "'\\''") + "'"


def draw_icon_png(path: Path, size: int = 1024) -> Path:
    """Paint a simple document-with-underlined-term icon as a PNG (needs a Qt GUI application)."""
    from PySide6.QtCore import QRectF, Qt
    from PySide6.QtGui import QColor, QFont, QGuiApplication, QImage, QPainter, QPen

    _app = QGuiApplication.instance() or QGuiApplication([])  # noqa: F841  (must exist while painting)
    image = QImage(size, size, QImage.Format.Format_ARGB32)
    image.fill(Qt.GlobalColor.transparent)
    p = QPainter(image)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    margin = size * 0.1
    # rounded page
    p.setPen(QPen(QColor("#9a9a9a"), size * 0.012))
    p.setBrush(QColor("#fdfdfb"))
    p.drawRoundedRect(QRectF(margin, margin * 0.8, size - 2 * margin, size - 1.6 * margin), size * 0.06, size * 0.06)
    # text lines
    p.setPen(QPen(QColor("#b8b8b8"), size * 0.028, Qt.PenStyle.SolidLine, Qt.PenCapStyle.RoundCap))
    x0, x1 = margin * 1.8, size - margin * 1.8
    for i, frac in enumerate([1.0, 0.85, 1.0, 0.6]):
        y = size * (0.26 + 0.09 * i)
        p.drawLine(QRectF(x0, y, (x1 - x0) * frac, 0).topLeft(), QRectF(x0, y, (x1 - x0) * frac, 0).topRight())
    # the underlined "term"
    font = QFont("Helvetica", int(size * 0.17), QFont.Weight.Bold)
    p.setFont(font)
    p.setPen(QColor("#1f3a5f"))
    rect = QRectF(x0, size * 0.62, x1 - x0, size * 0.2)
    p.drawText(rect, Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter, "para")
    width = p.fontMetrics().horizontalAdvance("para")
    p.setPen(QPen(QColor("#d9822b"), size * 0.03, Qt.PenStyle.SolidLine, Qt.PenCapStyle.RoundCap))
    y = size * 0.8
    p.drawLine(QRectF(x0, y, width, 0).topLeft(), QRectF(x0, y, width, 0).topRight())
    p.end()
    image.save(str(path))
    return path


def make_icns(dest: Path, work_dir: Path) -> Path | None:
    """Build ``dest`` (.icns) with ``iconutil``; return None where that tool is missing (not macOS)."""
    if shutil.which("iconutil") is None or shutil.which("sips") is None:
        return None
    iconset = work_dir / "paratext.iconset"
    iconset.mkdir(parents=True, exist_ok=True)
    master = draw_icon_png(work_dir / "icon_1024.png")
    for px in (16, 32, 128, 256, 512):
        for scale in (1, 2):
            name = f"icon_{px}x{px}{'@2x' if scale == 2 else ''}.png"
            subprocess.run(
                ["sips", "-z", str(px * scale), str(px * scale), str(master), "--out", str(iconset / name)],
                check=True,
                capture_output=True,
            )
    subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(dest)], check=True, capture_output=True)
    return dest


def build_app(dest: Path | None = None, python: str | None = None, path_env: str | None = None, icon=True) -> Path:
    """Write the bundle at ``dest`` (replacing an existing one) and return its path."""
    dest = Path(dest or default_app_path())
    python = python or sys.executable
    path_env = os.environ.get("PATH", "/usr/bin:/bin") if path_env is None else path_env
    if dest.suffix != ".app":
        raise ValueError(f"destination must end in .app: {dest}")
    if dest.exists():
        if not (dest / "Contents" / "Info.plist").exists():
            raise ValueError(f"{dest} exists and is not an app bundle; not replacing it")
        shutil.rmtree(dest)
    contents = dest / "Contents"
    (contents / "MacOS").mkdir(parents=True)
    (contents / "Resources").mkdir()

    launcher = contents / "MacOS" / EXECUTABLE
    launcher.write_text(LAUNCHER.format(path=_shell_quote(path_env), python=_shell_quote(python)))
    launcher.chmod(0o755)

    have_icon = False
    if icon:
        try:
            have_icon = make_icns(contents / "Resources" / ICON_FILE, contents / "Resources" / "_iconbuild") is not None
        finally:
            shutil.rmtree(contents / "Resources" / "_iconbuild", ignore_errors=True)
    with open(contents / "Info.plist", "wb") as f:
        plistlib.dump(info_plist(have_icon), f)
    (contents / "PkgInfo").write_text("APPL????")
    return dest


def register(app: Path) -> bool:
    """Tell Launch Services about the bundle so "Open With" shows it immediately. Returns False off macOS."""
    if not Path(LSREGISTER).exists():
        return False
    subprocess.run([LSREGISTER, "-f", str(app)], check=False, capture_output=True)
    return True
