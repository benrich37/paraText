"""Files linked to a paper: supporting-information PDFs, data files and folders.

Links are user data, not cache, so they live in the config directory (``$PARATEXT_LINKS`` or
``~/.config/paratext/links.json``), keyed by the paper's SHA-256 so they survive moving or renaming the PDF.
Editing the PDF in place (highlights saved by Preview, say) changes the hash; :meth:`LinkStore.adopt` then moves
the links recorded for that path and title over to the new hash.
"""

from __future__ import annotations

import contextlib
import functools
import hashlib
import json
import os
import tempfile
import threading
from dataclasses import asdict, dataclass
from datetime import datetime
from pathlib import Path

KINDS = ("pdf", "data", "folder")
#: data files whose contents are small text and can go into a prompt
TEXT_SUFFIXES = {
    ".txt", ".csv", ".tsv", ".md", ".json", ".xyz", ".dat", ".log", ".yaml", ".yml", ".toml", ".cif", ".xml",
    ".out", ".in", ".py", ".ini", ".cfg", ".tex", ".rst",
}  # fmt: skip
MAX_TEXT_FILE_BYTES = 2_000_000
MAX_FOLDER_ENTRIES = 200
#: every LinkStore in this process: each window has one, and engine workers write descriptions from their threads
_LOCK = threading.RLock()


def _locked(method):
    """Run a LinkStore method under the process-wide lock (read the file, change it, write it, as one step)."""

    @functools.wraps(method)
    def wrapper(*args, **kwargs):
        with _LOCK:
            return method(*args, **kwargs)

    return wrapper


def file_sha256(path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def default_links_path() -> Path:
    return Path(os.environ.get("PARATEXT_LINKS", Path.home() / ".config" / "paratext" / "links.json"))


@dataclass
class Link:
    path: str
    kind: str = "data"  # "pdf", "data" or "folder"
    label: str = ""
    added: str = ""
    #: what the file contains and when to consult it; written by the reader or generated by the AI
    description: str = ""
    #: "user" or the provider cache key that wrote the description
    description_by: str = ""

    @property
    def exists(self) -> bool:
        return Path(self.path).exists()

    @property
    def name(self) -> str:
        return self.label or Path(self.path).name


def kind_of(path) -> str:
    p = Path(path)
    if p.is_dir():
        return "folder"
    return "pdf" if p.suffix.lower() == ".pdf" else "data"


class LinkStore:
    """All links, keyed by document hash; saved on every change.

    Every window has its own store, so each call first re-reads the file if someone else changed it: a store
    holding an older copy must not write it back over links added elsewhere. Public methods run under a
    process-wide lock, because describe jobs write from worker threads while the window adds and removes links.
    """

    def __init__(self, path: Path | None = None):
        self.path = Path(path or default_links_path())
        self._data: dict[str, dict] = {}
        self._stamp = None
        self._fresh()

    def _file_stamp(self):
        try:
            st = self.path.stat()
        except OSError:
            return None
        return (st.st_mtime_ns, st.st_size)

    def _fresh(self) -> None:
        """Re-read the file when it changed since this store last read or wrote it."""
        stamp = self._file_stamp()
        if stamp == self._stamp:
            return
        self._stamp = stamp
        if stamp is None:
            self._data = {}
            return
        try:
            raw = json.loads(self.path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return
        docs = raw.get("documents", {}) if isinstance(raw, dict) else {}
        self._data = {k: v for k, v in docs.items() if isinstance(v, dict)}

    @_locked
    def save(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        text = json.dumps({"version": 1, "documents": self._data}, indent=1, ensure_ascii=False)
        fd, tmp = tempfile.mkstemp(dir=self.path.parent, prefix=self.path.name + ".", suffix=".tmp")
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                f.write(text)
            os.replace(tmp, self.path)
        except BaseException:
            with contextlib.suppress(OSError):
                os.unlink(tmp)
            raise
        self._stamp = self._file_stamp()

    @_locked
    def links(self, doc_hash: str) -> list[Link]:
        self._fresh()
        return [Link(**item) for item in self._data.get(doc_hash, {}).get("links", [])]

    def _stale_hashes(self, doc_hash: str, doc_path: str, title: str = "") -> list[str]:
        """Entries for the file at ``doc_path`` under other hashes (it was edited since), with a matching title."""
        return [
            h
            for h, entry in self._data.items()
            if h != doc_hash
            and entry.get("document") == doc_path
            and (not title or not entry.get("title") or entry.get("title") == title)
        ]

    @_locked
    def adopt(self, doc_hash: str, doc_path, title: str = "") -> int:
        """Move links recorded for this file under an older hash to ``doc_hash``; returns how many moved.

        A PDF edited in place (Preview saves highlights into the file) gets a new hash, which used to make its
        links disappear (reported issue, 2026-11-05). A link already under ``doc_hash`` wins over an old copy.
        """
        self._fresh()
        doc_path = str(Path(doc_path).expanduser().resolve())
        stale = self._stale_hashes(doc_hash, doc_path, title)
        entry = self._data.get(doc_hash)
        if entry is None and not stale:
            return 0
        entry = self._data.setdefault(doc_hash, {"document": doc_path, "links": []})
        changed = entry.get("document") != doc_path or (bool(title) and entry.get("title") != title)
        entry["document"] = doc_path
        if title:
            entry["title"] = title
        have = {item.get("path") for item in entry["links"]}
        moved = 0
        for h in stale:
            for item in self._data.pop(h).get("links", []):
                if item.get("path") not in have:
                    entry["links"].append(item)
                    have.add(item.get("path"))
                    moved += 1
            changed = True
        if changed:
            self.save()
        return moved

    @_locked
    def find(self, doc_hash: str, path) -> Link | None:
        path = str(Path(path).expanduser().resolve())
        return next((link for link in self.links(doc_hash) if link.path == path), None)

    @_locked
    def add(
        self,
        doc_hash: str,
        path,
        kind: str | None = None,
        doc_path: str = "",
        label: str = "",
        reciprocal: bool = True,
        doc_title: str = "",
    ) -> Link:
        """Link ``path`` to the document; re-linking an existing path keeps its description instead of duplicating.

        Linking a PDF is bidirectional: the document is also linked from that PDF (found by its hash), so opening
        the supporting information shows the main paper among its linked files.
        """
        self._fresh()
        path = str(Path(path).expanduser().resolve())
        kind = kind or kind_of(path)
        if kind not in KINDS:
            raise ValueError(f"kind must be one of {KINDS}, not {kind!r}")
        if doc_path:
            doc_path = str(Path(doc_path).expanduser().resolve())
        previous = self.find(doc_hash, path)
        entry = self._data.setdefault(doc_hash, {"document": doc_path, "links": []})
        if doc_path:
            entry["document"] = doc_path
        if doc_title:
            entry["title"] = doc_title
        link = Link(
            path,
            kind,
            label or (previous.label if previous else ""),
            datetime.now().isoformat(timespec="minutes"),
            previous.description if previous else "",
            previous.description_by if previous else "",
        )
        entry["links"] = [item for item in entry["links"] if item.get("path") != path] + [asdict(link)]
        self.save()
        if reciprocal and kind == "pdf" and doc_path and Path(path).is_file() and path != doc_path:
            other = file_sha256(path)
            if other != doc_hash and self.find(other, doc_path) is None:
                self.add(other, doc_path, "pdf", doc_path=path, reciprocal=False)
        return link

    @_locked
    def remove(self, doc_hash: str, path, reciprocal: bool = True) -> bool:
        self._fresh()
        path = str(Path(path).expanduser().resolve())
        entry = self._data.get(doc_hash)
        if not entry:
            return False
        doc_path = entry.get("document", "")
        before = len(entry["links"])
        removed = [item for item in entry["links"] if item.get("path") == path]
        entry["links"] = [item for item in entry["links"] if item.get("path") != path]
        if not entry["links"]:
            del self._data[doc_hash]
        self.save()
        if reciprocal and removed and removed[0].get("kind") == "pdf" and doc_path and Path(path).is_file():
            other = file_sha256(path)
            # the back-link may still sit under the linked PDF's hash from before it was edited
            for h in [other, *self._stale_hashes(other, path)]:
                self.remove(h, doc_path, reciprocal=False)
        return len(entry["links"]) != before

    @_locked
    def set_description(self, doc_hash: str, path, description: str, by: str = "user") -> bool:
        self._fresh()
        path = str(Path(path).expanduser().resolve())
        for item in self._data.get(doc_hash, {}).get("links", []):
            if item.get("path") == path:
                item["description"] = description.strip()
                item["description_by"] = by if description.strip() else ""
                self.save()
                return True
        return False


