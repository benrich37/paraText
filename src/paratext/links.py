def _pdf_text(path, max_chars: int) -> str:
    from paratext.pdf import PdfDocument

    doc = PdfDocument(path)
    try:
        text, truncated = doc.full_text(max_chars)
        return f"Title: {doc.title}\n{text}" + ("\n(truncated)" if truncated else "")
    finally:
        doc.close()


def link_body(link: Link, max_chars: int) -> str:
    """The content of a linked file as text: PDF text, a small text file, a folder listing, or a note."""
    p = Path(link.path)
    if not p.exists():
        return "(file not found)"
    if p.is_dir():
        names = sorted(x.name + ("/" if x.is_dir() else "") for x in p.iterdir())
        more = f"\n… and {len(names) - MAX_FOLDER_ENTRIES} more" if len(names) > MAX_FOLDER_ENTRIES else ""
        return "Folder contents:\n" + "\n".join(names[:MAX_FOLDER_ENTRIES]) + more
    if link.kind == "pdf" or p.suffix.lower() == ".pdf":
        try:
            return _pdf_text(p, max_chars)
        except Exception as e:  # a corrupt or non-PDF file must not break the question
            return f"(could not read as PDF: {e})"
    size = p.stat().st_size
    if p.suffix.lower() in TEXT_SUFFIXES and size <= MAX_TEXT_FILE_BYTES:
        text = p.read_text(errors="replace")
        return text[:max_chars] + ("\n(truncated)" if len(text) > max_chars else "")
    return f"({p.suffix.lstrip('.') or 'binary'} file, {size} bytes; contents not included)"


def link_context(links: list[Link], max_chars: int = 200_000) -> str:
    """``<linked_file>`` blocks for a prompt, sharing ``max_chars`` between them in link order."""
    parts, left = [], max_chars
    for link in links:
        if left <= 0:
            parts.append(
                f'<linked_file kind="{link.kind}" name="{link.name}" path="{link.path}">(omitted: no room)'
                "</linked_file>"
            )
            continue
        desc = f"Description: {link.description}\n" if link.description else ""
        body = link_body(link, left)
        chunk = f'<linked_file kind="{link.kind}" name="{link.name}" path="{link.path}">\n{desc}{body}\n</linked_file>'
        parts.append(chunk)
        left -= len(chunk)
    return "\n\n".join(parts)


def link_sample(link: Link, max_chars: int = 6000) -> str:
    """A short sample of a linked file, for the AI to describe it."""
    return link_body(link, max_chars)
