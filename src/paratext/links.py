"""Files linked to a paper: supporting-information PDFs, data files and folders.

Links are user data, not cache, so they live in the config directory (``$PARATEXT_LINKS`` or
``~/.config/paratext/links.json``), keyed by the paper's SHA-256 so they survive moving or renaming the PDF.
"""

from __future__ import annotations

import hashlib
import json
import os
from dataclasses import asdict, dataclass
from datetime import datetime
from pathlib import Path

KINDS = ("pdf", "data", "folder")
#: data files whose contents are small text and can go into a prompt
TEXT_SUFFIXES = {
    ".txt", ".csv", ".tsv", ".md", ".json", ".xyz", ".dat", ".log", ".yaml", ".yml", ".toml", ".cif", ".xml",
    ".out", ".in", ".py", ".ini", ".cfg", ".tex", ".rst",
}  # fmt: skip
MAX_TEXT_FILE_BYTES = 2_000_000
MAX_FOLDER_ENTRIES = 200


def file_sha256(path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def default_links_path() -> Path:
    return Path(os.environ.get("PARATEXT_LINKS", Path.home() / ".config" / "paratext" / "links.json"))


@dataclass
class Link:
    path: str
    kind: str = "data"  # "pdf", "data" or "folder"
    label: str = ""
    added: str = ""
    #: what the file contains and when to consult it; written by the reader or generated by the AI
    description: str = ""
    #: "user" or the provider cache key that wrote the description
    description_by: str = ""

    @property
    def exists(self) -> bool:
        return Path(self.path).exists()

    @property
    def name(self) -> str:
        return self.label or Path(self.path).name


def kind_of(path) -> str:
    p = Path(path)
    if p.is_dir():
        return "folder"
    return "pdf" if p.suffix.lower() == ".pdf" else "data"


class LinkStore:
    """All links, keyed by document hash; saved on every change."""

    def __init__(self, path: Path | None = None):
        self.path = Path(path or default_links_path())
        self._data: dict[str, dict] = {}
        self._load()

    def _load(self) -> None:
        if not self.path.exists():
            return
        try:
            raw = json.loads(self.path.read_text())
        except (OSError, json.JSONDecodeError):
            return
        docs = raw.get("documents", {}) if isinstance(raw, dict) else {}
        self._data = {k: v for k, v in docs.items() if isinstance(v, dict)}

    def save(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        tmp = self.path.with_suffix(".tmp")
        tmp.write_text(json.dumps({"version": 1, "documents": self._data}, indent=1, ensure_ascii=False))
        os.replace(tmp, self.path)

    def links(self, doc_hash: str) -> list[Link]:
        return [Link(**item) for item in self._data.get(doc_hash, {}).get("links", [])]

    def find(self, doc_hash: str, path) -> Link | None:
        path = str(Path(path).expanduser().resolve())
        return next((link for link in self.links(doc_hash) if link.path == path), None)

    def add(
        self,
        doc_hash: str,
        path,
        kind: str | None = None,
        doc_path: str = "",
        label: str = "",
        reciprocal: bool = True,
    ) -> Link:
        """Link ``path`` to the document; re-linking an existing path keeps its description instead of duplicating.

        Linking a PDF is bidirectional: the document is also linked from that PDF (found by its hash), so opening
        the supporting information shows the main paper among its linked files.
        """
        path = str(Path(path).expanduser().resolve())
        kind = kind or kind_of(path)
        if kind not in KINDS:
            raise ValueError(f"kind must be one of {KINDS}, not {kind!r}")
        if doc_path:
            doc_path = str(Path(doc_path).expanduser().resolve())
        entry = self._data.setdefault(doc_hash, {"document": doc_path, "links": []})
        if doc_path:
            entry["document"] = doc_path
        previous = self.find(doc_hash, path)
        link = Link(
            path,
            kind,
            label or (previous.label if previous else ""),
            datetime.now().isoformat(timespec="minutes"),
            previous.description if previous else "",
            previous.description_by if previous else "",
        )
        entry["links"] = [item for item in entry["links"] if item.get("path") != path] + [asdict(link)]
        self.save()
        if reciprocal and kind == "pdf" and doc_path and Path(path).is_file() and path != doc_path:
            other = file_sha256(path)
            if other != doc_hash and self.find(other, doc_path) is None:
                self.add(other, doc_path, "pdf", doc_path=path, reciprocal=False)
        return link

    def remove(self, doc_hash: str, path, reciprocal: bool = True) -> bool:
        path = str(Path(path).expanduser().resolve())
        entry = self._data.get(doc_hash)
        if not entry:
            return False
        doc_path = entry.get("document", "")
        before = len(entry["links"])
        removed = [item for item in entry["links"] if item.get("path") == path]
        entry["links"] = [item for item in entry["links"] if item.get("path") != path]
        if not entry["links"]:
            del self._data[doc_hash]
        self.save()
        if reciprocal and removed and removed[0].get("kind") == "pdf" and doc_path and Path(path).is_file():
            self.remove(file_sha256(path), doc_path, reciprocal=False)
        return len(entry["links"]) != before

    def set_description(self, doc_hash: str, path, description: str, by: str = "user") -> bool:
        path = str(Path(path).expanduser().resolve())
        for item in self._data.get(doc_hash, {}).get("links", []):
            if item.get("path") == path:
                item["description"] = description.strip()
                item["description_by"] = by if description.strip() else ""
                self.save()
                return True
        return False


